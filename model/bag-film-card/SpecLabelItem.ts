/**
 * 스펙 라벨 본문 한 줄에 필요한 값(BS-8).
 *
 * 뷰는 이 타입만 알면 되도록 모델에서 표시 형식까지 만들어 넘긴다 —
 * 뷰가 `Gear`를 직접 뒤지며 캐논컬/한글 폴백을 다시 판단하지 않게 하기 위함이다.
 */
export interface SpecLabelItem {
  // 대문자 브랜드. 영문·한글 모두 비어 있으면 빈 문자열이며, 뷰가 브랜드 줄을 비운다.
  brand: string;
  // 장비명.
  name: string;
  // 그램 단위 무게 표기(`1840g`).
  weightText: string;
  /**
   * 브랜드에 한글이 섞였는지.
   *
   * **영수증 템플릿에서는 쓰지 않는다** — D2Coding이 라틴·한글을 함께 담고 있어
   * 폰트를 갈아끼울 이유가 없다(BS-8). 폰트를 다시 라틴 전용으로 바꾸는 안이 나오면
   * 필요해지므로 판정 자체는 남겨 둔다.
   */
  hasKoreanBrand: boolean;
}
